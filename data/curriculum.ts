export function getTopicsForLevel(level: CurriculumLevel): TopicConfig[] {
  return TOPICS_BY_LEVEL[level] || [];
}

export function getTopicConfig(level: CurriculumLevel, topicId: TopicId | string): TopicConfig | undefined {
  const topics = getTopicsForLevel(level);
  return topics.find((t) => t.id === topicId);
}
